"""
Plot FEAST source-tracking results and connect them to functional metrics.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from matplotlib.gridspec import GridSpec
from scipy.stats import spearmanr

import analysis_expansion_utils as aeu


def main() -> None:
    outdir = aeu.SOURCE_TRACKING_DIR
    long_path = outdir / "feast_source_contributions.tsv"
    linkage_path = outdir / "function_linkage_space.tsv"
    if not long_path.exists():
        raise FileNotFoundError(
            "FEAST long-format output not found. Run 23_run_feast.R after installing FEAST."
        )

    long_df = pd.read_csv(long_path, sep="\t")
    linkage_df = pd.read_csv(linkage_path, sep="\t")
    linkage_df = linkage_df.drop(columns=["sample_type", "location"], errors="ignore")

    pivot = long_df.pivot_table(
        index="SampleID", columns="Source", values="Contribution", aggfunc="sum"
    ).fillna(0)
    sink_meta = long_df[["SampleID", "sample_type", "location"]].drop_duplicates()
    plot_df = sink_meta.merge(pivot, on="SampleID", how="left").merge(
        linkage_df, on="SampleID", how="left"
    )

    source_cols = [col for col in pivot.columns if col != "unknown"]
    dominant_source = plot_df[source_cols].mean().sort_values(ascending=False).index[0]

    fig = plt.figure(figsize=(18, 11))
    gs = GridSpec(2, 2, figure=fig, hspace=0.35, wspace=0.28)

    ax_a = fig.add_subplot(gs[0, 0])
    ax_b = fig.add_subplot(gs[0, 1])
    ax_c = fig.add_subplot(gs[1, 0])
    ax_d = fig.add_subplot(gs[1, 1])

    ax_a.axis("off")
    ax_a.text(
        0.0,
        1.0,
        "A   Source Tracking Design\n\n"
        "Sinks:\n"
        "- Plant Roots\n"
        "- Rhizosphere\n\n"
        "Primary sources:\n"
        "- Arcillite\n"
        "- Wick\n"
        "- Water\n"
        "- seed\n"
        "- Swab\n"
        "- Foam\n\n"
        "This plot uses FEAST contributions generated by 23_run_feast.R.",
        va="top",
        ha="left",
        fontsize=11,
    )

    ordered_samples = (
        plot_df.sort_values(["sample_type", "location", "SampleID"])["SampleID"].tolist()
    )
    stacked = plot_df.set_index("SampleID").loc[ordered_samples, source_cols + ["unknown"]]
    bottom = np.zeros(len(stacked))
    palette = sns.color_palette("tab20", n_colors=stacked.shape[1])
    for color, source in zip(palette, stacked.columns):
        values = stacked[source].values
        ax_b.bar(range(len(stacked)), values, bottom=bottom, color=color, width=0.9, label=source)
        bottom += values
    ax_b.set_title("B   Per-sink Source Fractions", loc="left", fontsize=11, fontweight="bold")
    ax_b.set_ylabel("Contribution")
    ax_b.set_xticks(range(len(stacked)))
    ax_b.set_xticklabels(ordered_samples, rotation=90, fontsize=7)
    ax_b.legend(frameon=False, fontsize=7, bbox_to_anchor=(1.02, 1), loc="upper left")

    summary = (
        long_df.groupby(["sample_type", "location", "Source"])["Contribution"]
        .mean()
        .reset_index()
    )
    summary["sink_cycle"] = summary["sample_type"] + "_" + summary["location"]
    heat = summary.pivot(index="Source", columns="sink_cycle", values="Contribution").fillna(0)
    sns.heatmap(heat, cmap="YlOrBr", ax=ax_c, linewidths=0.5, linecolor="white")
    ax_c.set_title("C   Mean Source Fractions by Sink and Cycle", loc="left", fontsize=11, fontweight="bold")
    ax_c.set_xlabel("")
    ax_c.set_ylabel("")

    ax_d.scatter(
        plot_df[dominant_source],
        plot_df["nitrification_abundance"],
        s=65,
        alpha=0.8,
        color="#2b7bba",
        edgecolor="white",
        linewidth=0.8,
    )
    rho, p_value = spearmanr(
        plot_df[dominant_source].fillna(0).values,
        plot_df["nitrification_abundance"].fillna(0).values,
    )
    ax_d.set_title(
        f"D   Exploratory Dominant Source vs Nitrification ({dominant_source})",
        loc="left",
        fontsize=11,
        fontweight="bold",
    )
    ax_d.set_xlabel(f"{dominant_source} contribution")
    ax_d.set_ylabel("Nitrification abundance (%)")
    ax_d.text(
        0.03,
        0.97,
        f"Spearman $\\rho$ = {rho:.2f}\np = {p_value:.3f}",
        transform=ax_d.transAxes,
        va="top",
        ha="left",
        fontsize=9,
        bbox={"boxstyle": "round,pad=0.25", "facecolor": "white", "edgecolor": "#cccccc"},
    )

    out_png = outdir / "Fig_SourceTracking.png"
    out_pdf = outdir / "Fig_SourceTracking.pdf"
    fig.savefig(out_png, dpi=300, bbox_inches="tight")
    fig.savefig(out_pdf, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved: {out_png}")
    print(f"Saved: {out_pdf}")


if __name__ == "__main__":
    main()
